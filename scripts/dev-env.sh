detect_container_cli() {
  if command -v docker >/dev/null 2>&1; then
    printf docker
  elif command -v podman >/dev/null 2>&1; then
    printf podman
  fi
}

detect_branch() {
  git -C "$ROOT" branch --show-current 2>/dev/null || true
}

detect_owner_repo() {
  git -C "$ROOT" remote get-url origin 2>/dev/null \
    | sed -E 's#^(git@github.com:|https://github.com/|ssh://git@github.com/)##; s#\.git$##' \
    | tr '[:upper:]' '[:lower:]' || true
}

branch_tag() {
  local branch="$1"
  local base suffix prefix
  base="$(printf '%s' "$branch" | sed -E 's#[^A-Za-z0-9_.-]+#-#g; s#^-+##; s#-+$##')"
  [ -n "$base" ] || base=local
  suffix="$(printf '%s' "$branch" | sha256sum | cut -c1-12)"
  prefix="$(printf '%s' "$base" | cut -c1-115 | sed -E 's#-+$##')"
  [ -n "$prefix" ] || prefix=local
  printf '%s-%s' "$prefix" "$suffix"
}

