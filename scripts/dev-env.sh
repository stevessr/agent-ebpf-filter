shell_quote() {
  local value="$1"
  printf "'"
  printf "%s" "$value" | sed "s/'/'\\\\''/g"
  printf "'"
}

make_escape() {
  local value="$1"
  value="${value//'$'/'$$'}"
  value="${value//'#'/'\#'}"
  value="${value//$'\n'/ }"
  printf "%s" "$value"
}

